"""Render reports/temporal_bias.md (Step 4 part B) from the generated tables only.

Inputs: the CSVs and eval_bias_facts.json that src/eval_bias_report.py wrote. Every number in the
report is read from them, and the sentences that make a claim ("closer", "inside the CI",
"collapses") are chosen by code from those numbers, so the text follows the results if they change.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

from config import N_BOOTSTRAP, REPORTS, RUN_SUFFIX, SEED, TABLES

MODEL_NAMES: dict[str, str] = {"lgbm_default": "LightGBM default", "logreg": "LogReg", "grid": "LightGBM grid",
                               "random": "LightGBM random", "optuna": "LightGBM Optuna", "flaml": "FLAML",
                               "autogluon": "AutoGluon", "h2o": "H2O AutoML"}
N_FEATURES: int = 2568  # thrember feature vector length (src.data.feature_groups())
TREE_MODELS: list[str] = ["lgbm_default", "grid", "random", "optuna", "flaml", "autogluon", "h2o"]


# --- Reading and formatting ---------------------------------------------------------------
def _csv(stem: str) -> pd.DataFrame:
    path = TABLES / f"{stem}{RUN_SUFFIX}.csv"
    if not path.exists():
        raise FileNotFoundError(f"{path} missing: run scripts/run_eval_bias.py --stages tables")
    return pd.read_csv(path)


def _facts() -> dict[str, Any]:
    return json.loads((TABLES / f"eval_bias_facts{RUN_SUFFIX}.json").read_text(encoding="utf-8"))


def _f4(x: Any) -> str:
    return "n/a" if pd.isna(x) else f"{float(x):.4f}"


def _pct(x: Any, digits: int = 1) -> str:
    return "n/a" if pd.isna(x) else f"{100 * float(x):.{digits}f}%"


def _pp(x: Any) -> str:
    return "n/a" if pd.isna(x) else f"{100 * float(x):+.2f} pp"


def _abs_pp(x: Any) -> str:
    return "n/a" if pd.isna(x) else f"{100 * float(x):.2f} pp"


def _ci(row: pd.Series, col: str, fmt=_f4) -> str:
    return f"{fmt(row[col])} [{fmt(row[col + '_ci_low'])}, {fmt(row[col + '_ci_high'])}]"


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _name(model: str) -> str:
    return MODEL_NAMES.get(model, model)


def _excludes_zero(row: pd.Series, col: str) -> bool:
    return bool(row[f"{col}_ci_low"] > 0 or row[f"{col}_ci_high"] < 0)


# --- Sections -----------------------------------------------------------------------------
